"""
Robustness checks added for the camera-ready version.

Reviewers asked what happens when the data are not generated by the Gaussian
model of the main text.  This script varies

  * the outcome law            (Gaussian, Student-t(3), skewed log-normal, binary)
  * the partition              (6, 12, 24 histogram cells)
  * the collective's spread    (equal means, unequal variance)
  * the degree of coordination (half of the recruited members ignore the instruction)
  * idiosyncratic defiers      (uncoordinated defiers with complier outcomes)
  * exclusion                  (a direct effect of the encouragement, no defiers)

and reports the population bound V(P), the first stage, the Wald estimand, and
the rejection rate of the moment-inequality test at three experiment sizes.
It also prints the worked binary example of Appendix B and checks it against
the linear program and against the Richardson--Robins (2010) bound.

    python3 robustness.py            # full run (~47 s locally, 400 replications)
    python3 robustness.py --quick    # coarse smoke test

Outputs: results_robustness.json and tab_robustness.tex
"""

from __future__ import annotations

import argparse
import json
import pathlib
from dataclasses import dataclass

import numpy as np
from scipy import stats
from scipy.integrate import quad

import audit as A

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "results_robustness.json"
TAB = HERE / "tab_robustness.tex"

LEVEL = 0.05
NS = (2_000, 10_000, 50_000)
N_BINS = 12

# ---------------------------------------------------------------- shapes
# Every continuous family is standardized to mean 0 and variance 1 so that
# ``sep`` and ``tau`` mean the same thing across families.
_LN_S = 0.75
_LN_MEAN = float(np.exp(_LN_S ** 2 / 2))
_LN_SD = float(np.sqrt((np.exp(_LN_S ** 2) - 1.0) * np.exp(_LN_S ** 2)))
_T_DF = 3
_T_SCALE = float(np.sqrt(_T_DF / (_T_DF - 2)))


def shape_pdf(family: str, x: np.ndarray) -> np.ndarray:
    if family == "gaussian":
        return stats.norm.pdf(x)
    if family == "t3":
        return stats.t.pdf(x * _T_SCALE, df=_T_DF) * _T_SCALE
    if family == "lognormal":
        u = x * _LN_SD + _LN_MEAN
        out = np.zeros_like(np.asarray(x, dtype=float))
        ok = u > 0
        out[ok] = stats.lognorm.pdf(u[ok], s=_LN_S) * _LN_SD
        return out
    raise ValueError(family)


def shape_rvs(family: str, size: int, rng: np.random.Generator) -> np.ndarray:
    if family == "gaussian":
        return rng.standard_normal(size)
    if family == "t3":
        return rng.standard_t(_T_DF, size) / _T_SCALE
    if family == "lognormal":
        return (np.exp(_LN_S * rng.standard_normal(size)) - _LN_MEAN) / _LN_SD
    raise ValueError(family)


def shape_cdf(family: str, x: np.ndarray) -> np.ndarray:
    if family == "gaussian":
        return stats.norm.cdf(x)
    if family == "t3":
        return stats.t.cdf(x * _T_SCALE, df=_T_DF)
    if family == "lognormal":
        return stats.lognorm.cdf(x * _LN_SD + _LN_MEAN, s=_LN_S)
    raise ValueError(family)


# ---------------------------------------------------------------- model
@dataclass
class RobustDGP:
    """Platform experiment with a planted collective; generalizes audit.DGP.

    Units are grouped into six kinds, (D(0), D(1), outcome law):
        a   always-taker  (1,1) law 'a'
        n   never-taker   (0,0) law 'n'
        c   complier      (0,1) law 'c'
        f   active collective member: defier (1,0) with the collective law 'f'
        cp  passive collective member: complier (0,1) with the collective law 'f'
        fi  idiosyncratic defier: defier (1,0) with the complier law 'c'
    Total defier mass is alpha + idio.
    """

    family: str = "gaussian"
    alpha: float = 0.10
    passive: float = 0.0
    idio: float = 0.0
    pi_c: float = 0.30
    pi_a: float = 0.25
    sep: float = 1.0            # location shift of the collective law
    tau: float = 1.0            # complier effect
    tau_f: float | None = None  # collective effect (defaults to tau)
    sigma_f: float = 1.0        # scale of the collective law
    direct: float = 0.0         # direct effect of Z on Y (exclusion failure)
    # binary family: success probabilities
    # binary family defaults reproduce the worked example of Appendix B
    p_c: tuple[float, float] = (0.40, 0.20)   # complier success prob. for d=0, d=1
    p_f: tuple[float, float] = (0.40, 0.90)   # collective success prob. for d=0, d=1
    p_a1: float = 0.50
    p_n0: float = 0.60

    def __post_init__(self) -> None:
        if self.tau_f is None:
            self.tau_f = self.tau
        if self.pi_n < -1e-12:
            raise ValueError("shares exceed one")

    @property
    def pi_n(self) -> float:
        return 1.0 - self.alpha - self.passive - self.idio - self.pi_c - self.pi_a

    def units(self) -> list[tuple[str, float, int, int, str]]:
        return [
            ("a", self.pi_a, 1, 1, "a"),
            ("n", self.pi_n, 0, 0, "n"),
            ("c", self.pi_c, 0, 1, "c"),
            ("f", self.alpha, 1, 0, "f"),
            ("cp", self.passive, 0, 1, "f"),
            ("fi", self.idio, 1, 0, "c"),
        ]

    # continuous laws ------------------------------------------------------
    def loc_scale(self, law: str, d: int, z: int) -> tuple[float, float]:
        shift = self.direct * z
        if law == "c":
            return (self.tau * d + shift, 1.0)
        if law == "f":
            return (self.sep + self.tau_f * d + shift, self.sigma_f)
        if law == "a":
            return (0.5 + shift, 1.0)
        if law == "n":
            return (-0.5 + shift, 1.0)
        raise ValueError(law)

    # binary laws ----------------------------------------------------------
    def p1(self, law: str, d: int, z: int) -> float:
        shift = self.direct * z
        if law == "c":
            p = self.p_c[d]
        elif law == "f":
            p = self.p_f[d]
        elif law == "a":
            p = self.p_a1
        elif law == "n":
            p = self.p_n0
        else:
            raise ValueError(law)
        return float(np.clip(p + shift, 0.0, 1.0))

    def mean(self, law: str, d: int, z: int) -> float:
        if self.family == "binary":
            return self.p1(law, d, z)
        return self.loc_scale(law, d, z)[0]

    # population quantities ------------------------------------------------
    def cells(self) -> tuple[dict[str, np.ndarray], np.ndarray]:
        """Population densities on a finite grid, or exact binary cell masses.

        Continuous arrays are densities, not normalized cell probabilities;
        use ``cell_masses`` for a finite partition, including its tail cells.
        """
        if self.family == "binary":
            grid = np.array([0.0, 1.0])

            def law_mass(law: str, d: int, z: int) -> np.ndarray:
                p = self.p1(law, d, z)
                return np.array([1.0 - p, p])
        else:
            grid = np.linspace(-14.0, 16.0, 60001)

            def law_mass(law: str, d: int, z: int) -> np.ndarray:
                loc, scale = self.loc_scale(law, d, z)
                return shape_pdf(self.family, (grid - loc) / scale) / scale

        m = {k: np.zeros_like(grid) for k in ("m11", "m10", "m00", "m01")}
        for _, share, d0, d1, law in self.units():
            if share <= 0.0:
                continue
            if d1 == 1:
                m["m11"] += share * law_mass(law, 1, 1)
            else:
                m["m01"] += share * law_mass(law, 0, 1)
            if d0 == 1:
                m["m10"] += share * law_mass(law, 1, 0)
            else:
                m["m00"] += share * law_mass(law, 0, 0)
        return m, grid

    def violation(self) -> float:
        """Unrestricted V(P); quadrature covers the full continuous support."""
        if self.family == "binary":
            return A.cellwise_V(self.cells()[0])

        laws = {key: [] for key in ("m11", "m10", "m00", "m01")}
        breaks = set()
        for _, share, d0, d1, law in self.units():
            if share == 0.0:
                continue
            for z, d in ((0, d0), (1, d1)):
                key = f"m{d}{z}"
                loc, scale = self.loc_scale(law, d, z)
                laws[key].append((share, loc, scale))
                breaks.add(loc)
                if self.family == "lognormal":
                    breaks.add(loc - scale * _LN_MEAN / _LN_SD)

        def density(key: str, y: float) -> float:
            return sum(share * float(shape_pdf(self.family, np.asarray((y - loc) / scale))) / scale
                       for share, loc, scale in laws[key])

        edges = [-np.inf, *sorted(breaks), np.inf]
        values = []
        for positive, negative in (("m10", "m11"), ("m01", "m00")):
            values.append(sum(quad(lambda y: max(density(positive, y) - density(negative, y), 0.0),
                                   a, b, epsabs=1e-10, epsrel=1e-8, limit=200)[0]
                              for a, b in zip(edges[:-1], edges[1:])))
        return max(values)

    def cell_masses(self, n_bins: int = N_BINS) -> dict[str, np.ndarray]:
        """Exact population probabilities for the partition used by the test."""
        if self.family == "binary":
            return self.cells()[0]
        edges = np.linspace(*A.Y_RANGE, n_bins + 1)
        edges[0], edges[-1] = -np.inf, np.inf
        m = {key: np.zeros(n_bins) for key in ("m11", "m10", "m00", "m01")}
        for _, share, d0, d1, law in self.units():
            for z, d in ((0, d0), (1, d1)):
                loc, scale = self.loc_scale(law, d, z)
                key = f"m{d}{z}"
                m[key] += share * np.diff(shape_cdf(self.family, (edges - loc) / scale))
        return m

    def first_stage(self) -> float:
        return sum(s * (d1 - d0) for _, s, d0, d1, _ in self.units())

    def wald(self) -> float:
        rf = sum(s * (self.mean(law, d1, 1) - self.mean(law, d0, 0))
                 for _, s, d0, d1, law in self.units())
        fs = self.first_stage()
        return rf / fs if abs(fs) > 1e-12 else float("nan")

    def complier_effect(self) -> float:
        """Average effect among all compliers (baseline compliers plus passive members)."""
        num = self.pi_c * (self.mean("c", 1, 0) - self.mean("c", 0, 0))
        num += self.passive * (self.mean("f", 1, 0) - self.mean("f", 0, 0))
        return num / (self.pi_c + self.passive)

    @property
    def defier_mass(self) -> float:
        return self.alpha + self.idio

    # sampling -------------------------------------------------------------
    def sample(self, n: int, rng: np.random.Generator) -> dict[str, np.ndarray]:
        units = self.units()
        shares = np.clip(np.array([u[1] for u in units]), 0.0, None)
        kind = rng.choice(len(units), size=n, p=shares / shares.sum())
        z = rng.integers(0, 2, size=n)
        d = np.zeros(n, dtype=int)
        y = np.empty(n)
        for i, (_, _, d0, d1, law) in enumerate(units):
            sel = kind == i
            if not sel.any():
                continue
            d[sel] = np.where(z[sel] == 1, d1, d0)
            for zz in (0, 1):
                for dd in (0, 1):
                    s = sel & (z == zz) & (d == dd)
                    k = int(s.sum())
                    if not k:
                        continue
                    if self.family == "binary":
                        y[s] = rng.random(k) < self.p1(law, dd, zz)
                    else:
                        loc, scale = self.loc_scale(law, dd, zz)
                        y[s] = loc + scale * shape_rvs(self.family, k, rng)
        return {"z": z, "d": d, "y": y.astype(float), "t": kind}


def test_kwargs(g: RobustDGP, n_bins: int) -> dict:
    if g.family == "binary":
        return {"n_bins": 2, "y_range": (-0.5, 1.5)}
    return {"n_bins": n_bins, "y_range": A.Y_RANGE}


def rejection_rate(g: RobustDGP, n: int, reps: int, n_draws: int, seed: int,
                   n_bins: int = N_BINS) -> float:
    rng = np.random.default_rng(seed)
    kw = test_kwargs(g, n_bins)
    rej = [A.gaussian_moment_test(g.sample(n, rng), level=LEVEL, n_draws=n_draws,
                                  rng=rng, **kw)["reject"] for _ in range(reps)]
    return float(np.mean(rej))


# ---------------------------------------------------------------- scenarios
SCENARIOS: list[tuple[str, str, dict]] = [
    # (row label, outcome-law label, DGP kwargs)
    ("sep $=1$ (baseline)", "Gaussian", dict(family="gaussian", sep=1.0)),
    ("exact mimicry", "Gaussian", dict(family="gaussian", sep=0.0)),
    ("sep $=1$", "Student-$t_3$", dict(family="t3", sep=1.0)),
    ("exact mimicry", "Student-$t_3$", dict(family="t3", sep=0.0)),
    ("sep $=1$", "log-normal", dict(family="lognormal", sep=1.0)),
    ("exact mimicry", "log-normal", dict(family="lognormal", sep=0.0)),
    ("App.~\\ref{app:example} example", "binary", dict(family="binary")),
    ("exact mimicry", "binary", dict(family="binary", p_f=(0.40, 0.20))),
    ("equal means, $\\sigma_f=2$", "Gaussian", dict(family="gaussian", sep=0.0, sigma_f=2.0)),
    ("sep $=1$, $80\\%$ participation", "Gaussian",
     dict(family="gaussian", sep=1.0, alpha=0.08, passive=0.02)),
    ("sep $=1$, $50\\%$ participation", "Gaussian",
     dict(family="gaussian", sep=1.0, alpha=0.05, passive=0.05)),
    ("sep $=3$, $\\alpha=0.05$", "Gaussian",
     dict(family="gaussian", sep=3.0, alpha=0.05)),
    ("sep $=3$, $\\alpha=0.05$, $+0.05$ idiosyncratic", "Gaussian",
     dict(family="gaussian", sep=3.0, alpha=0.05, idio=0.05)),
    ("none; direct effect $0.1$", "Gaussian", dict(family="gaussian", alpha=0.0, direct=0.1)),
    ("none; direct effect $0.3$", "Gaussian", dict(family="gaussian", alpha=0.0, direct=0.3)),
]

PARTITION_BINS = (6, 12, 24)


def run_scenarios(reps: int, n_draws: int, ns: tuple[int, ...]) -> list[dict]:
    rows = []
    for i, (label, law, kw) in enumerate(SCENARIOS):
        g = RobustDGP(**kw)
        row = {
            "label": label, "law": law, "kwargs": kw,
            "defier_mass": g.defier_mass, "V": g.violation(),
            "V_partition": A.cellwise_V(g.cell_masses()),
            "first_stage": g.first_stage(), "wald": g.wald(),
            "complier_effect": g.complier_effect(),
            "reject": {str(n): rejection_rate(g, n, reps, n_draws, 20_000 + 101 * i + j)
                       for j, n in enumerate(ns)},
        }
        rows.append(row)
        print(f"  {law:12s} {label:55s} V={row['V']:.4f} FS={row['first_stage']:.2f} "
              f"rej={[round(v, 2) for v in row['reject'].values()]}")
    return rows


def run_partition(reps: int, n_draws: int, n: int = 10_000) -> dict:
    out = {}
    for label, kw in (("separated", dict(family="gaussian", sep=1.0)),
                      ("mimicry", dict(family="gaussian", sep=0.0))):
        g = RobustDGP(**kw)
        out[label] = {str(b): rejection_rate(g, n, reps, n_draws, 30_000 + 7 * b, n_bins=b)
                      for b in PARTITION_BINS}
        print(f"  partition {label}: {out[label]}")
    return out


def run_boundary_null(reps: int, n_draws: int) -> dict:
    """All cell moments bind: equal complier/defier mass and identical laws.

    This checks calibration at an observed-distribution boundary of the null;
    interior exact-mimicry scenarios alone cannot establish boundary behavior.
    """
    kwargs = dict(family="gaussian", alpha=0.10, pi_c=0.10, sep=0.0)
    g = RobustDGP(**kwargs)
    rates = {str(n): rejection_rate(g, n, reps, n_draws, 40_000 + j)
             for j, n in enumerate((500, 2_000, 10_000))}
    print(f"  boundary null: {rates}")
    return {"kwargs": kwargs, "V": g.violation(), "reject": rates}


# ---------------------------------------------------------------- worked example
def worked_example() -> dict:
    """Binary example of Appendix B, checked three ways."""
    pi = {"a": 0.25, "n": 0.35, "c": 0.30, "f": 0.10}
    p1 = {("a", 1): 0.5, ("n", 0): 0.6, ("c", 1): 0.2, ("c", 0): 0.4,
          ("f", 1): 0.9, ("f", 0): 0.4}

    def mass(t: str, d: int) -> np.ndarray:
        p = p1[(t, d)]
        return pi[t] * np.array([1.0 - p, p])

    m = {"m11": mass("a", 1) + mass("c", 1), "m10": mass("a", 1) + mass("f", 1),
         "m00": mass("n", 0) + mass("c", 0), "m01": mass("n", 0) + mass("f", 0)}
    S1, S0 = m["m10"] - m["m11"], m["m01"] - m["m00"]
    V = A.cellwise_V(m)
    lp_lo, lp_hi = A.defier_mass_identified_set(m, 2)

    # Richardson & Robins (2010), eq. (16): pi_DE = P(D=1|Z=0) - pi_AT with
    # pi_AT <= u_{pi_AT}; the six terms of u are listed in the order of the paper.
    px1z0, px1z1 = m["m10"].sum(), m["m11"].sum()
    u_terms = [
        px1z0, px1z1,
        1.0 - (m["m00"][0] + m["m01"][1]),       # 1 - sum_j p(y=j, x=0 | z=j)
        1.0 - (m["m01"][0] + m["m00"][1]),       # 1 - sum_k p(y=k, x=0 | z=1-k)
        m["m10"][0] + m["m11"][1],               # sum_j p(y=j, x=1 | z=j)
        m["m11"][0] + m["m10"][1],               # sum_k p(y=k, x=1 | z=1-k)
    ]
    rr_lower_de = px1z0 - min(u_terms)

    rf = (m["m11"][1] + m["m01"][1]) - (m["m10"][1] + m["m00"][1])
    fs = px1z1 - px1z0
    tau_c = p1[("c", 1)] - p1[("c", 0)]
    tau_f = p1[("f", 1)] - p1[("f", 0)]
    wald_formula = (pi["c"] * tau_c - pi["f"] * tau_f) / (pi["c"] - pi["f"])
    delta = pi["f"] - pi["c"]
    attaining = {"f": V, "c": V - delta, "a": px1z0 - V, "n": (1 - px1z1) - V}
    out = {
        "shares": pi, "success_probs": {f"{t}{d}": v for (t, d), v in p1.items()},
        "cells": {k: v.tolist() for k, v in m.items()},
        "S1": S1.tolist(), "S0": S0.tolist(), "V": V,
        "lp_min_defier_mass": lp_lo, "lp_max_defier_mass": lp_hi,
        "rr_u_terms": u_terms, "rr_lower_bound_defiers": rr_lower_de,
        "reduced_form": rf, "first_stage": fs, "wald": rf / fs,
        "tau_c": tau_c, "tau_f": tau_f, "wald_formula": wald_formula,
        "attaining_model_shares": attaining,
        "attaining_shares_sum": sum(attaining.values()),
    }
    assert abs(V - lp_lo) < 1e-7, (V, lp_lo)
    assert abs(V - rr_lower_de) < 1e-12, (V, rr_lower_de)
    assert abs(rf / fs - wald_formula) < 1e-12
    assert abs(out["attaining_shares_sum"] - 1.0) < 1e-12
    # Measure domination can hide a sign flip even without exact mimicry.
    hidden = RobustDGP(family="binary", p_c=(0.4, 0.6), p_f=(0.0, 1.0))
    hidden_m = hidden.cell_masses()
    out["hidden_signflip"] = {
        "cells": {key: value.tolist() for key, value in hidden_m.items()},
        "V": hidden.violation(), "first_stage": hidden.first_stage(),
        "wald": hidden.wald(), "tau_c": hidden.complier_effect(), "tau_f": 1.0,
        "lp_min_defier_mass": A.defier_mass_identified_set(hidden_m, 2)[0],
    }
    assert out["hidden_signflip"]["V"] == 0.0
    assert abs(out["hidden_signflip"]["wald"] + 0.2) < 1e-12
    assert abs(out["hidden_signflip"]["tau_c"] - 0.2) < 1e-12
    return out


# ---------------------------------------------------------------- table
def fmt(x: float, nd: int = 2) -> str:
    return f"{x:.{nd}f}"


def write_table(rows: list[dict], partition: dict, ns: tuple[int, ...], reps: int) -> None:
    lines = [
        "% Auto-generated by code/robustness.py -- do not edit by hand.",
        "\\begin{tabular}{@{}llrrrrrrr@{}}",
        "\\toprule",
        "Outcome law & Collective & $\\Prob(T{=}f)$ & $V(P)$ & FS & Wald & "
        + " & ".join(f"$n{{=}}{n:,}$".replace(",", "{,}") for n in ns) + "\\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(
            f"{r['law']} & {r['label']} & {fmt(r['defier_mass'])} & {fmt(r['V'], 3)} & "
            f"{fmt(r['first_stage'])} & {fmt(r['wald'])} & "
            + " & ".join(fmt(r['reject'][str(n)]) for n in ns) + "\\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    TAB.write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--table-only", action="store_true",
                    help="rewrite the LaTeX table from results_robustness.json")
    args = ap.parse_args()
    if args.table_only:
        prev = json.loads(OUT.read_text())
        for i, row in enumerate(prev["scenarios"]):
            row["label"], row["law"] = SCENARIOS[i][0], SCENARIOS[i][1]
        OUT.write_text(json.dumps(prev, indent=2))
        write_table(prev["scenarios"], prev["partition_n10000"],
                    tuple(prev["config"]["ns"]), prev["config"]["reps"])
        print(f"rewrote {TAB}")
        return
    reps = 20 if args.quick else 400
    n_draws = 300 if args.quick else 1000
    ns = (2_000, 10_000) if args.quick else NS

    print("worked binary example ...")
    ex = worked_example()
    print(f"  V(P)={ex['V']:.4f}  LP min={ex['lp_min_defier_mass']:.4f}  "
          f"R&R lower bound={ex['rr_lower_bound_defiers']:.4f}  Wald={ex['wald']:.3f}")
    print("robustness scenarios ...")
    rows = run_scenarios(reps, n_draws, ns)
    print("partition sensitivity ...")
    part = run_partition(reps, n_draws)
    print("boundary-null calibration ...")
    boundary = run_boundary_null(reps, n_draws)
    results = {"config": {"reps": reps, "n_gaussian_draws": n_draws, "ns": list(ns),
                          "level": LEVEL, "n_bins": N_BINS, "quick": args.quick,
                          "lognormal_sigma": _LN_S, "t_df": _T_DF},
               "worked_example": ex, "scenarios": rows, "partition_n10000": part,
               "boundary_null": boundary}
    OUT.write_text(json.dumps(results, indent=2))
    write_table(rows, part, ns, reps)
    print(f"wrote {OUT} and {TAB}")


if __name__ == "__main__":
    main()
